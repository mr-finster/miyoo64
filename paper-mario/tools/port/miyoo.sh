#!/bin/sh
# The Miyoo Mini release zip of Paper Mario (README_MIYOO.md, notes/miyoo.md): PaperMario-miyoo.zip at the repo root.
#
#   sh tools/port/miyoo.sh            the public zip (code and numbers only; the ROM is read for the leak scan)
#   PERSONAL=1 sh tools/port/miyoo.sh the same with the ROM inside as App/PaperMario/rom.z64: PaperMario-miyoo-PERSONAL.zip,
#                                     for your own card only (never share it)
#   ROM=<file>                        the ROM (default "Paper Mario (USA).z64" at the repo root; read, never shipped)
#   REUSE=1                           pack the last build again (no rebuild, the same stamp): PERSONAL=1 REUSE=1 after the
#                                     public zip gives the same files plus rom.z64
#   NO_LEAK_SCAN=1                    no ROM at hand: gate 4 skipped, PaperMario-miyoo-UNSCANNED.zip, not a release
#
# Needs: the decomp split (refs/papermario at the pinned commit with game/patches/decomp.patch, ./configure us run with
# your ROM: README.md, "Building"), build/game/rom_segments.json (tools/port/rom_segments.py), clang (the game side, as the
# Mac step), the Miyoo toolchain at MIYOO_TOOLCHAIN (default /opt/miyoomini-toolchain: gcc 8.3, glibc 2.28, the device's
# SDL 1.2), ninja.
#
# The game side is the handheld's, object for object (gen_build.py: build/game/handheld_game.mk), so the asset region is the
# handheld build's and its recipes (tools/assets/recipes_handheld.json) fit when this machine's compile matches the one they
# were derived from. When it doesn't (another clang lays the region out differently) they are derived again from the ROM
# into tools/assets/recipes_miyoo.json, never over the handheld's file.
#
# Then the release gates (as DKR's/OoT's Miyoo gates), all fatal, on what really ships: the zip is
# packed to a temporary file, unpacked, checked, and only then put in place.
#   1. provenance: refs/papermario is the pinned commit plus exactly game/patches/decomp.patch, every other source
#      compiled into the executable is tracked in git (or generated by gen_build.py from those), and so are the packer,
#      its templates, miyoo/game.json and the icon;
#   2. the asset region is NOBITS (no game data in the executable), and no shared-library variable is copied (R_ARM_COPY)
#      into the save-state range (__data_start to the asset region, the dontsave section aside) but glibc's stdin,
#      stdout and stderr (savestate.c keeps the live ones);
#   3. only what the game needs to run: App/PaperMario holds exactly game.json's files plus the packer's launch.sh,
#      config.json and icon.png (and rom.z64 in a PERSONAL zip); no text files anywhere;
#   4. leak scan: no 32-byte window of any file in the zip matches the ROM inside an asset-region symbol, and the rest
#      (the decompiled code's own tables) stays within the handheld's budget (tools/assets/leak_scan.py);
#   5. no authoring metadata or host paths in any file in the zip.
set -eu
cd "$(dirname "$0")/../.."
ROOT=$(pwd)
PERSONAL=${PERSONAL:-0}
NO_LEAK_SCAN=${NO_LEAK_SCAN:-0}
ROM=${ROM:-Paper Mario (USA).z64}
MTC=${MIYOO_TOOLCHAIN:-/opt/miyoomini-toolchain}
TC=$MTC/usr/bin/arm-linux-gnueabihf
B=build/game/miyoo
GAME=miyoo/game.json
FOLDER=PaperMario
OUT=PaperMario-miyoo.zip
if [ "$PERSONAL" = 1 ]; then OUT=PaperMario-miyoo-PERSONAL.zip
elif [ "$NO_LEAK_SCAN" = 1 ]; then OUT=PaperMario-miyoo-UNSCANNED.zip; fi
rm -f "$OUT" # a failed gate must not leave the last zip in place looking like this build's
test -x "$TC-gcc" || { echo "ERROR: the Miyoo toolchain is not at $TC-* (set MIYOO_TOOLCHAIN)"; exit 1; }
test -f refs/papermario/build.ninja || { echo "ERROR: no decomp split: ./configure us in refs/papermario with your ROM (README.md, "Building")"; exit 1; }
if [ ! -f "$ROM" ]; then
    if [ "$NO_LEAK_SCAN" = 1 ] && [ "$PERSONAL" != 1 ]; then echo "WARNING: no ROM at $ROM: gate 4 SKIPPED, $OUT is not a release"
    else echo "ERROR: ROM $ROM missing (set ROM=<file>; it is read for the leak scan and the recipes, never shipped)"; exit 1; fi
fi

if [ "${REUSE:-0}" = 1 ]; then # pack the last build again (the PERSONAL zip of the same binary as the public one)
    test -x $B/pm64 && test -f $B/recipes.bin && test -f $B/assets.bin || { echo "ERROR: REUSE=1 but no build in $B"; exit 1; }
    STAMP=$(sed -n 's/.*0x\([0-9a-f]*\);/\1/p' $B/build_stamp.c)
    BID=$(python3 -c 'import struct,sys; print(struct.unpack_from("<8sIIIIIIIII", open(sys.argv[1],"rb").read(), 0)[7])' $B/assets.bin)
    RECIPES=""
    for r in tools/assets/recipes_handheld.json tools/assets/recipes_miyoo.json; do
        [ -f "$r" ] && [ "$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("build_id"))' "$r")" = "$BID" ] && { RECIPES=$r; break; }
    done
    echo "--- reusing the build in $B (stamp $STAMP, recipes $RECIPES) ---"
else
echo "--- build ---"
# through /work (the build container's mount): the generated files then name /work, not this
# machine's home, so no host path reaches the build (gate 5)
[ "$(cd /work 2>/dev/null && pwd -P)" = "$(pwd -P)" ] || { echo "ERROR: /work must be this repo (ln -sfn $ROOT /work)"; exit 1; }
python3 /work/tools/port/gen_build.py handheld > /dev/null
python3 /work/tools/port/gen_build.py miyoo > /dev/null
mkdir -p $B
STAMP=$(od -An -N4 -tx4 /dev/urandom | tr -d ' ')
printf '#include <stdint.h>\nconst uint32_t port_build_stamp = 0x%s;\n' "$STAMP" > $B/build_stamp.c
rm -f $B/pm64 $B/pm64_assets.elf $B/recipes.bin $B/assets.bin
# clang 18 (newer than the Mac's) makes -Wreturn-type an error (the decomp's sprite.c returns no value in two places);
# downgraded here, a diagnostic only: the code it compiles is the same
GAME_CC="$(sed -n 's/^CC := //p' build/game/handheld_game.mk) -Wno-error=return-type"
if ! make -f build/game/handheld_game.mk CC="$GAME_CC" -j"$(nproc)" -k > $B/game_make.log 2>&1; then
    grep -E "error|FAILED|No rule" $B/game_make.log | head -20
    echo "miyoo.sh: the game side did not build (all of it: $B/game_make.log)"; exit 1
fi
ninja -f build/game/miyoo.ninja -k 0 /work/$B/pm64 /work/$B/pm64_assets.elf | grep -v '^\[' || true
test -x $B/pm64 && test -f $B/pm64_assets.elf || { echo "miyoo.sh: the link failed"; exit 1; }
python3 tools/assets/make_assets.py $B/pm64_assets.elf $B/pm64 -o $B/assets.bin --page 4096
BID=$(python3 -c 'import struct,sys; print(struct.unpack_from("<8sIIIIIIIII", open(sys.argv[1],"rb").read(), 0)[7])' $B/assets.bin)
RECIPES=""
for r in tools/assets/recipes_handheld.json tools/assets/recipes_miyoo.json; do
    [ -f "$r" ] && [ "$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("build_id"))' "$r")" = "$BID" ] && { RECIPES=$r; break; }
done
if [ -z "$RECIPES" ]; then
    [ -f "$ROM" ] || { echo "ERROR: no recipes for this asset layout (build id $BID) and no ROM to derive them"; exit 1; }
    echo "the asset layout ($BID) is not the handheld recipes': deriving tools/assets/recipes_miyoo.json from the ROM"
    mkdir -p refs/sc
    python3 tools/assets/derive_recipes.py $B/assets.bin "$ROM" -o tools/assets/recipes_miyoo.json \
        --cache refs/sc/mio0cache.pkl --report refs/sc/derive_report_miyoo.txt | tail -12
    RECIPES=tools/assets/recipes_miyoo.json
fi
echo "recipes: $RECIPES (layout $BID)"
python3 tools/assets/emit_recipes.py "$RECIPES" $B/assets.bin -o $B/recipes.bin --stamp "$STAMP"
fi

echo "--- gate 1: provenance ---"
PIN=ee321921d
bad=0
[ "$(git -C refs/papermario rev-parse HEAD)" = "$(git -C refs/papermario rev-parse $PIN)" ] || { echo "refs/papermario is not at $PIN"; bad=1; }
git -C refs/papermario diff $PIN -- . > $B/decomp_now.patch
cmp -s $B/decomp_now.patch game/patches/decomp.patch || { echo "refs/papermario's changes are not game/patches/decomp.patch"; bad=1; }
n=0
for f in $(sed -n 's|^build [^:]*: cc_host /work/||p' build/game/miyoo.ninja) $(sed -n 's|^build [^:]*: cc_game_port /work/||p' build/game/handheld.ninja); do
    n=$((n + 1))
    case "$f" in build/game/port_segtab.c|build/game/port_effects.c|build/game/miyoo/build_stamp.c) continue ;; esac
    git ls-files --error-unmatch "$f" >/dev/null 2>&1 || { echo "UNTRACKED source in the executable: $f"; bad=$((bad + 1)); }
done
for f in game/port/*.c game/port/*.h kit/platform/*.c kit/platform/*.h bench/kit/*.c bench/kit/*.h; do
    git ls-files --error-unmatch "$f" >/dev/null 2>&1 || { echo "UNTRACKED port file: $f"; bad=$((bad + 1)); }
done
for f in "$GAME" miyoo/tools/miyoo_pack.py miyoo/templates/* miyoo/icon.png tools/port/gen_build.py "$RECIPES"; do
    git ls-files --error-unmatch "$f" >/dev/null 2>&1 || { echo "UNTRACKED packer input: $f"; bad=$((bad + 1)); }
done
echo "provenance: decomp $PIN + decomp.patch, $n host/port sources, $bad problems"
[ "$n" -ge 20 ] || { echo "ERROR: only $n sources listed - the check did not run"; exit 1; }
[ "$bad" -eq 0 ] || exit 1

echo "--- gate 2: the asset region and the save-state range ---"
"$TC-readelf" -SW $B/pm64 | grep -E '\.assetdata +NOBITS' >/dev/null || { echo "ERROR: .assetdata is not NOBITS: the executable carries game data"; exit 1; }
sym() { "$TC-nm" $B/pm64 | awk -v s="$1" '$3 == s { print $1; exit }'; }
DS=$(sym __data_start); AS=$(sym __assets_start); XS=$(sym __start_dontsave); XE=$(sym __stop_dontsave)
[ -n "$DS" ] && [ -n "$AS" ] && [ -n "$XS" ] && [ -n "$XE" ] || { echo "ERROR: save-state range symbols missing"; exit 1; }
BAD=$("$TC-readelf" -rW $B/pm64 | awk '$3 == "R_ARM_COPY" { print $1, $5 }' | while read -r a name; do
    v=$((0x$a))
    if [ $v -ge $((0x$DS)) ] && [ $v -lt $((0x$AS)) ] && ! { [ $v -ge $((0x$XS)) ] && [ $v -lt $((0x$XE)) ]; }; then
        case "$name" in stdin*|stdout*|stderr*) ;; *) echo "  $name at 0x$a" ;; esac
    fi
done)
[ -z "$BAD" ] || { echo "ERROR: shared-library variables copied into the save-state range:"; echo "$BAD"; exit 1; }
COPIES=$("$TC-readelf" -rW $B/pm64 | awk '$3 == "R_ARM_COPY" { printf "%s ", $5 }')
echo ".assetdata NOBITS; state range 0x$DS-0x$AS minus dontsave 0x$XS-0x$XE; copies: ${COPIES:-none}"

STAGE=build/miyoo_stage; UNPACK=build/miyoo_unpack; TMPZIP=build/miyoo_pack.zip
rm -rf "$STAGE" "$UNPACK" "$TMPZIP"; mkdir -p "$STAGE" "$UNPACK"
cp $B/pm64 "$STAGE/pm64"
"$TC-strip" --strip-all --remove-section=.comment "$STAGE/pm64"
chmod +x "$STAGE/pm64"
cp $B/recipes.bin "$STAGE/recipes.bin"

echo "--- pack (to a temporary zip, checked below) ---"
set -- "$GAME" --build "$STAGE" -o "$TMPZIP"
[ "$PERSONAL" = 1 ] && set -- "$@" --rom "$ROM"
python3 miyoo/tools/miyoo_pack.py "$@"
python3 - "$TMPZIP" "$UNPACK" <<'PY'
import os, sys, zipfile
with zipfile.ZipFile(sys.argv[1]) as z:
    for i in z.infolist():
        n = os.path.normpath(i.filename)
        if n.startswith('..') or os.path.isabs(n):
            sys.exit('zip entry outside the card root: %s' % i.filename)
    z.extractall(sys.argv[2])
PY

echo "--- gate 3: only what the game needs to run ---"
want=$(python3 -c 'import json,sys; print(" ".join(sorted(json.load(open(sys.argv[1]))["files"])))' "$GAME")
have=$(cd "$STAGE" && ls -A | sort | tr '\n' ' ' | sed 's/ $//')
[ "$have" = "$want" ] || { echo "ERROR: staged files '$have' are not exactly '$want'"; exit 1; }
extra=""; [ "$PERSONAL" = 1 ] && extra=rom.z64
WANT_APP=$(printf '%s\n' $want launch.sh config.json icon.png $extra | sort | tr '\n' ' ')
GOT_APP=$(cd "$UNPACK/App/$FOLDER" && ls -A | sort | tr '\n' ' ')
[ "$GOT_APP" = "$WANT_APP" ] || { echo "ERROR: App/$FOLDER holds [$GOT_APP], not [$WANT_APP]"; exit 1; }
TEXT=$(cd "$UNPACK" && find . -type f | grep -i -E '(\.md|\.txt|/readme[^/]*|/notice[^/]*|/licen[cs]e[^/]*)$' || true)
[ -z "$TEXT" ] || { echo "ERROR: text files in the zip:"; echo "$TEXT"; exit 1; }
echo "App/$FOLDER: $GOT_APP"

echo "--- gate 4: leak scan of every file in the zip against the ROM ---"
if [ -f "$ROM" ]; then
    # a PERSONAL zip carries the ROM itself on purpose: everything else is scanned (the executable as it ships,
    # its hits named from the unstripped link)
    find "$UNPACK" -type f ! -path "*/App/$FOLDER/rom.z64" ! -path "*/App/$FOLDER/pm64" -print0 > build/miyoo_scan.lst
    xargs -0 python3 tools/assets/leak_scan.py --rom "$ROM" --assets $B/assets.bin --budget-kb ${LEAK_BUDGET_KB:-48} < build/miyoo_scan.lst
    python3 tools/assets/leak_scan.py --rom "$ROM" --assets $B/assets.bin --symbols-from $B/pm64 --budget-kb ${LEAK_BUDGET_KB:-48} \
        "$UNPACK/App/$FOLDER/pm64"
else
    echo "SKIPPED (NO_LEAK_SCAN=1, no ROM): $OUT is not a release"
fi

echo "--- gate 5: no authoring metadata or host paths in the zip ---"
if find "$UNPACK" -type f ! -path "*/App/$FOLDER/rom.z64" -print0 | xargs -0 grep -l -a -E 'xmpmeta|Photoshop|/Users/|/home/|/root/'; then
    echo "ERROR: identifying metadata in the files above"; exit 1
fi
echo "clean"

mv "$TMPZIP" "$OUT"
echo "--- contents ---"
python3 - "$OUT" <<'PY'
import sys, zipfile
with zipfile.ZipFile(sys.argv[1]) as z:
    for i in z.infolist():
        print('%10d  %o  %s' % (i.file_size, i.external_attr >> 16 & 0o777, i.filename))
PY
ls -la "$OUT"; md5sum "$OUT"
echo "build stamp $STAMP"
[ "$PERSONAL" = 1 ] && echo "$OUT CONTAINS YOUR ROM: keep it to yourself"
[ -f "$ROM" ] || echo "NOT A RELEASE: the leak scan did not run (no ROM)"
