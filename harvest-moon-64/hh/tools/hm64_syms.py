#!/usr/bin/env python3
"""hm64_syms.py <hm64.elf> <out.ld>: linker PROVIDEs for the native build, from the matching N64 ELF.

- every segment symbol (_xxxSegmentRomStart/End, ...Start, ...Size): the game passes ROM addresses to nuPiReadRom,
  and the port's DMA reads them from the data pack, which keeps the ROM's layout;
- every N64 RAM buffer (src/buffers/*.c, not compiled natively) at its N64 address: the port maps the N64's RAM
  at 0x80000000 (hh_ram.c), where the game also reaches these buffers through numeric addresses (buffers.h).
Reads no ROM: symbol values only. Needs mips-linux-gnu-nm.
"""
import glob, os, subprocess, sys

def nm(path):
    out = subprocess.run(['mips-linux-gnu-nm', path], capture_output=True, text=True, check=True).stdout
    syms = {}
    for line in out.splitlines():
        p = line.split()
        if len(p) == 3:
            syms[p[2]] = (int(p[0], 16), p[1])
    return syms

def main():
    elf, out = sys.argv[1], sys.argv[2]
    syms = nm(elf)
    buffers = set()
    for o in glob.glob(os.path.join(os.path.dirname(os.path.abspath(elf)), 'build/src/buffers/*.o')):
        for name, (v, t) in nm(o).items():
            if t in 'BbDdCc':
                buffers.add(name)
    lines = ['/* generated by hh/tools/hm64_syms.py from the N64 ELF: segment symbols and the N64 RAM buffers */']
    n_seg = n_buf = 0
    for name in sorted(syms):
        v, t = syms[name]
        if name.startswith('_') and 'Segment' in name:
            lines.append(f'PROVIDE({name} = 0x{v:08X});')
            n_seg += 1
        elif name in buffers:
            lines.append(f'PROVIDE({name} = 0x{v:08X});')
            n_buf += 1
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(f'hm64_syms: {n_seg} segment symbols, {n_buf} buffers')

if __name__ == '__main__':
    main()
