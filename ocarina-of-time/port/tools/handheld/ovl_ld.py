#!/usr/bin/env python3
"""ovl_ld.py <src/overlays dir> <gamestate.ld> <out.ld>

The port links every overlay in, so an overlay's .data/.bss are never reloaded the way the N64 reloads them each
time it loads the overlay (src/port/hh/hh_ovl.c restores them instead). This writes the save-state linker script
with each overlay's .data and .bss gathered between symbols, ahead of the template's catch-all overlay rules:

    __hhovl_<dir>_ds / _de   (.data)      __hhovl_<dir>_bs / _be   (.bss)

for every src/overlays/<kind>/<dir>. The rest of the template is copied unchanged (still the save-state ranges).
"""
import os
import sys


def main():
    ovl_root, template, out = sys.argv[1:4]
    dirs = []
    for kind in sorted(os.listdir(ovl_root)):
        kd = os.path.join(ovl_root, kind)
        if not os.path.isdir(kd):
            continue
        for d in sorted(os.listdir(kd)):
            if os.path.isdir(os.path.join(kd, d)):
                dirs.append((kind, d))
    text = open(template).read()
    data_rule = "    */src/overlays/*(.data .data.*)\n"
    bss_rule = "    */src/overlays/*(.bss .bss.*)\n"
    if text.count(data_rule) != 1 or text.count(bss_rule) != 1:
        sys.exit("ovl_ld.py: the template's overlay rules were not found once each")

    def block(sec, a, b):
        lines = []
        for kind, d in dirs:
            lines.append("    __hhovl_%s_%s = .;\n" % (d, a))
            lines.append("    */src/overlays/%s/%s/*(.%s .%s.*)\n" % (kind, d, sec, sec))
            lines.append("    __hhovl_%s_%s = .;\n" % (d, b))
        return "".join(lines)

    text = text.replace(data_rule, block("data", "ds", "de") + data_rule)
    text = text.replace(bss_rule, block("bss", "bs", "be") + bss_rule)
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    tmp = out + ".tmp"
    with open(tmp, "w") as f:
        f.write("/* generated by tools/handheld/ovl_ld.py from %s */\n" % os.path.basename(template))
        f.write(text)
    if os.path.exists(out) and open(out).read() == open(tmp).read():
        os.remove(tmp)
    else:
        os.replace(tmp, out)


if __name__ == "__main__":
    main()
