#!/usr/bin/env python3
"""Segment tables for the port link, from the decomp's own N64 build outputs.

Reads the splat linker script (which asset bank sits at which segment base)
and the N64 ELF built from the player's ROM (every *_ROM_START/_ROM_END: the
offsets of each file in the decompressed ROM). Writes numbers only:

  banks.mk     BANKS := name ...; BANK_VRAM_<name> := 0x06000000; BANK_SIZE_<name>
  n64_asset_syms.ld  PROVIDE()s for cross-bank references (bank links)
  rom_syms.ld  <seg>_ROM_START / _ROM_END = absolute decompressed-ROM offsets,
               and the asset banks' _VRAM / _VRAM_END (their segment bases).

The port ROM image keeps the decompressed ROM's layout, so these offsets are
the port's DMA addresses too (see src/port/sf64/port_rom.c).
"""
import re, subprocess, sys

ld_path, elf_path, nm, out_dir = sys.argv[1:5]
ld = open(ld_path).read()

# .ast_corneria 0x6000000 : AT(...)   -- banks linked at a segment base
banks = [(m.group(1), int(m.group(2), 16))
         for m in re.finditer(r'^\s+\.(ast_\w+) (0x[0-9A-Fa-f]+) : AT', ld, re.M)]

syms = {}
for line in subprocess.run([nm, elf_path], capture_output=True, text=True, check=True).stdout.splitlines():
    p = line.split()
    if len(p) == 3:
        syms[p[2]] = int(p[0], 16)

segs = sorted({m.group(1) for m in re.finditer(r'^\s+(\w+)_ROM_START = __romPos;', ld, re.M)})
with open(f'{out_dir}/rom_syms.ld', 'w') as f:
    f.write('/* generated by tools/handheld/gen_segments.py: numbers only */\n')
    for s in segs:
        f.write(f'{s}_ROM_START = 0x{syms[s + "_ROM_START"]:08X};\n')
        f.write(f'{s}_ROM_END = 0x{syms[s + "_ROM_END"]:08X};\n')
    for name, vram in banks:
        size = syms[name + '_ROM_END'] - syms[name + '_ROM_START']
        f.write(f'{name}_VRAM = 0x{vram:08X};\n{name}_VRAM_END = 0x{vram + size:08X};\n')

with open(f'{out_dir}/banks.mk', 'w') as f:
    f.write('# generated by tools/handheld/gen_segments.py\n')
    f.write('BANKS := ' + ' '.join(n for n, _ in banks) + '\n')
    for name, vram in banks:
        size = syms[name + '_ROM_END'] - syms[name + '_ROM_START']
        f.write(f'BANK_VRAM_{name} := 0x{vram:08X}\nBANK_SIZE_{name} := {size}\n')
# Cross-bank references (a Titania bank drawing another Titania bank's
# textures): the N64 resolves them in its one big link. Each port bank is
# linked alone, so give it every N64 symbol in the segment window as a
# fallback -- its own definitions win, and they are at the same addresses.
with open(f'{out_dir}/n64_asset_syms.ld', 'w') as f:
    f.write('/* generated by tools/handheld/gen_segments.py: numbers only */\n')
    for name, addr in sorted(syms.items()):
        if 0x01000000 <= addr < 0x10000000 and re.match(r'^[A-Za-z_]\w*$', name):
            f.write(f'PROVIDE({name} = 0x{addr:08X});\n')

print(f'gen_segments: {len(banks)} banks, {len(segs)} ROM segments')
