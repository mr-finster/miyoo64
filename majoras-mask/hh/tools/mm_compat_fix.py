#!/usr/bin/env python3
"""mm_compat_fix.py <base.elf> <new.elf> <base build ids, one a line: the base release and earlier pinned ones> <out.c>: the compat table for hh_state_compat.c.

Every 32-bit word of .game_data whose initial value differs between the base release and this build (both linked
at the same addresses: mm_pin_ld.py), as (address, base value, new value). With <base.elf> "-", an empty table
(the build loads only its own states).
"""
import struct, subprocess, sys, os

OBJCOPY = os.environ.get('OBJCOPY', '/opt/miyoomini-toolchain/usr/bin/arm-linux-gnueabihf-objcopy')
READELF = os.environ.get('READELF', '/opt/miyoomini-toolchain/usr/bin/arm-linux-gnueabihf-readelf')


def section(path, name):
    data = subprocess.run([OBJCOPY, '-O', 'binary', '-j', name, path, '/dev/stdout'], capture_output=True).stdout
    addr = None
    for l in subprocess.run([READELF, '-SW', path], capture_output=True, text=True).stdout.split('\n'):
        p = l.replace('[', ' ').replace(']', ' ').split()
        if len(p) > 4 and p[1] == name:
            addr = int(p[3], 16)
    return addr, data


def main():
    base, new, build, out = sys.argv[1:5]
    rows = []
    if base != '-':
        ab, db = section(base, '.game_data')
        an, dn = section(new, '.game_data')
        if ab != an or len(db) != len(dn):
            sys.exit('mm_compat_fix.py: .game_data differs in place or size (%s/%d vs %s/%d): not a pinned build'
                     % (ab, len(db), an, len(dn)))
        for i in range(0, len(db) - 3, 4):
            if db[i:i + 4] != dn[i:i + 4]:
                rows.append((ab + i, struct.unpack_from('<I', db, i)[0], struct.unpack_from('<I', dn, i)[0]))
    with open(out, 'w') as f:
        f.write('/* generated by hh/tools/mm_compat_fix.py: .game_data words that differ from the base release */\n')
        f.write('#include <stdint.h>\n#include <stddef.h>\n')
        f.write('typedef struct { uint32_t addr, from, to; } HhCompatFix;\n')
        ids = [b.strip() for b in build.split('\n') if b.strip()] if base != '-' else []
        f.write('const char *const kHhCompatBuilds[] = { %s NULL };\n' % ''.join('"%s", ' % b for b in ids))
        f.write('const HhCompatFix kHhCompatFix[] = {\n')
        for a, x, y in rows:
            f.write('    { 0x%08Xu, 0x%08Xu, 0x%08Xu },\n' % (a, x, y))
        f.write('    { 0, 0, 0 }\n};\n')
        f.write('const uint32_t kHhCompatFixCount = %du;\n' % len(rows))
    print('mm_compat_fix.py: %d words' % len(rows))


if __name__ == '__main__':
    main()
