#!/usr/bin/env python3
"""Linker script of PROVIDE()s from the matching N64 ELF: every asset symbol at its segmented address, every
ROM file's vrom start/end, and the overlays' VRAM/ROM symbols as 0 (the overlays are linked into the
executable, so the game takes its "not an overlay" paths). PROVIDE only fills symbols the port leaves
undefined. usage: mm_syms.py <n64 elf> <out.ld>"""
import re, subprocess, sys

elf, out = sys.argv[1], sys.argv[2]
syms = {}
for line in subprocess.run(["mips-linux-gnu-nm", elf], capture_output=True, text=True, check=True).stdout.splitlines():
    p = line.split()
    if len(p) == 3 and p[1].isupper() and re.match(r"^[A-Za-z_]\w*$", p[2]):
        syms.setdefault(p[2], int(p[0], 16))
with open(out, "w") as f:
    f.write("/* generated by hh/tools/mm_syms.py from the N64 ELF */\n")
    for n, v in sorted(syms.items()):
        if re.match(r"^_ovl_\w+Segment(Rom)?(Start|End)$", n):
            v = 0
        elif re.match(r"^(Sequence|SampleBank|Soundfont)_\d+_(Start|Size)$", n):
            pass  # the audio tables' entries: offsets in Audioseq/Audiotable/Audiobank (the first is 0)
        elif not (0x00000000 < v < 0x10000000) and not re.match(r"^_\w+SegmentRom(Start|End)$", n):
            continue
        f.write("PROVIDE(%s = 0x%08X);\n" % (n, v))
