#!/usr/bin/env python3
"""Emit gSineTable / gArcTanTable (1025 x s16 each) as C.

On the N64 these live in src/hasm/ido/math_util.s. They are closed-form
tables, and these formulas reproduce all 1025 entries of each bit-exactly
(checked against the decomp source on 2026-09-23, see BUILDLOG round 1), so
the port generates them instead of carrying the ROM's bytes.
"""
import math

def rnd(x):  # round half away from zero (no entry sits on .5, but be explicit)
    return int(math.floor(x + 0.5))

sine = [rnd(32768 * math.sin(i * math.pi / 2 / 1024)) for i in range(1025)]
atan = [rnd(0x2000 * math.atan(i / 1024) / (math.pi / 4)) for i in range(1025)]
assert sine[0] == 0 and sine[1] == 0x32 and sine[1024] == 0x8000
assert atan[1] == 10 and atan[1024] == 0x2000

def emit(name, vals):
    print("s16 %s[1025] = {" % name)
    for i in range(0, len(vals), 12):
        print("    " + ", ".join("(s16) 0x%04X" % v for v in vals[i:i + 12]) + ",")
    print("};\n")

print("/* Generated by tools/gen_trig_tables.py -- do not edit. */")
print('#include "types.h"\n')
emit("gSineTable", sine)
emit("gArcTanTable", atan)
