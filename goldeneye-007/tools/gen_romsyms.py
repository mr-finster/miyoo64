#!/usr/bin/env python3
"""Generate port/hh/romsyms_u.s: the ROM-layout symbols of the retail NTSC-U build.

The game code takes the address of symbols that, on the console, are ROM offsets or
segment-relative addresses rather than RAM objects:
  - linker-script segment bounds: ROM offsets (`_gameSegmentRomStart`, ...) passed to
    romCopy(), and VMAs whose differences are segment sizes (`_fontbankgothicSegmentEnd`
    - `...Start`) or that are addresses (`_bssSegmentEnd` = 0x8008E360, where the N64's
    memory pool starts -- inside the port's DRAM block at the same address);
  - labels in the ROM-image objects (ob_seg.o file labels like `CarmourguardZ`, ramrom
    demos, music tables, romfiles2), also ROM offsets;
  - symbols inside the nine segment objects M1 rebuilds (`dlBasicGeometry` = 0x01000000,
    `ANIM_DATA_idle` = 0x1C, `s_skywaterimages` = 0x02000FB4, ...), segment addresses.
The port links none of those objects, so it gets the same values as absolute symbols.
Source: the M1 link map (tools/m1_build.sh), which is byte-verified against the ROM.
Output is numbers only.

Usage: tools/gen_romsyms.py <ge007.u.map> <out.s>
"""
import re, sys

ROM_OBJECTS = (
    "assets/obseg/ob_seg.o", "assets/ramrom/ramrom.o", "assets/romfiles2.o",
    "assets/font_dl.o", "assets/font_chardataj.o", "assets/font_chardatae.o",
    "assets/animationtable_entries.o", "assets/animationtable_data.o",
    "assets/oddtextures.o", "assets/rarewarelogo.o",
    "assets/font/fontBankGothic.o", "assets/font/fontZurichBold.o",
)

def main() -> int:
    mp, out = sys.argv[1], sys.argv[2]
    syms = {}
    cur_obj = None
    for line in open(mp):
        m = re.match(r"^ \.\S+\s+0x[0-9a-f]+\s+0x[0-9a-f]+ build/u/(\S+)$", line) or \
            re.match(r"^\s+0x[0-9a-f]+\s+0x[0-9a-f]+ build/u/(\S+)$", line)
        if m:
            cur_obj = m.group(1); continue
        m = re.match(r"^\s+0x([0-9a-f]{8})\s+(\S+) = ", line)          # script assignment
        if m and "Segment" in m.group(2):
            syms[m.group(2)] = int(m.group(1), 16); continue
        m = re.match(r"^\s+0x([0-9a-f]{8})\s+([A-Za-z_][A-Za-z0-9_]*)$", line)  # symbol in section
        if m and cur_obj and (cur_obj in ROM_OBJECTS or cur_obj.startswith("assets/music/")):
            syms[m.group(2)] = int(m.group(1), 16)
    with open(out, "w") as f:
        f.write("/* GENERATED by tools/gen_romsyms.py from the byte-verified M1 link map.\n"
                " * ROM offsets and segment addresses of the retail NTSC-U layout (numbers only). */\n")
        for name, val in sorted(syms.items(), key=lambda kv: (kv[1], kv[0])):
            f.write(f".global {name}\n.set {name}, 0x{val:08x}\n")
        f.write('.section .note.GNU-stack,"",%progbits\n')
    print(f"{out}: {len(syms)} symbols")
    return 0

if __name__ == "__main__":
    sys.exit(main())
